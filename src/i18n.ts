// Standard Galactic Alphabet letter map (lowercase Latin to SGA glyphs).
const galactic: Record<string, string> = {
  a: 'ᔑ', b: 'ʖ', c: 'ᓵ', d: '↸', e: 'ᒷ', f: '⎓', g: '⊣', h: '⍑', i: '╎', j: '⋮', k: 'ꖌ', l: 'ꖎ', m: 'ᒲ',
  n: 'リ', o: '𝙹', p: '!¡', q: 'ᑑ', r: '∷', s: 'ᓭ', t: 'ℸ ̣', u: '⚍', v: '⍊', w: '∴', x: ' ̇/', y: '||', z: '⨅',
}

// Keep the product name readable in every script.
export function toGalactic(text: string) {
  return text
    .split(/(c@t)/g)
    .map((part) => (part === 'c@t' ? part : part.replace(/[a-z]/gi, (ch) => galactic[ch.toLowerCase()] ?? ch)))
    .join('')
}

const dicts: Partial<Record<LangCode, Dict>> = { en, fr, es, it, de, pt, pl, sk, ru, ar, hi, ja, ga }

export function translator(code: LangCode) {
  return (key: StringKey) => {
    if (code === 'sga') return toGalactic(en[key])
    return dicts[code]?.[key] ?? en[key]
  }
}

export function plainText(code: LangCode, key: StringKey) {
  // Text sent to speech synthesis: Galactic glyphs cannot be spoken, so read the English source.
  return code === 'sga' ? en[key] : translator(code)(key)
}
